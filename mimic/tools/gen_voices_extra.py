#!/usr/bin/env python3
"""Voices for every subtitle that had none: Sam's inner voice (line.*) and the cutscene lines that are not one of the
story's voiced lines. Same voices (Kokoro) and the same treatment as gen_sounds.py. Run after gen_sounds.py, which
starts the sounds folder from scratch.

Events: "v.you.<key>" for line.<key>, "v.cut.<cut>.<n>" for cut.<cut>.<n>. Writes registry/ExtraVoices.java with the names.

usage: gen_voices_extra.py <tts_dir with kokoro.onnx+voices.bin> <hatman sounds dir>
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TTS, HMDIR = sys.argv[1], sys.argv[2]
sys.argv = [sys.argv[0], TTS, TTS, HMDIR]
sys.path.insert(0, HERE)
import gen_sounds as g
import gen_lang

EN = os.path.join(g.A, "lang/en_us.json")
JAVA = os.path.join(HERE, "../common/src/main/java/com/krolasyon/mimic/registry/ExtraVoices.java")
CUTS = os.path.join(HERE, "../common/src/main/java/com/krolasyon/mimic/story/Cutscenes.java")
WORK = os.path.join(TTS, "work_extra")
os.makedirs(WORK, exist_ok=True)

# the inner voice: close to the ear, quiet, a breath of room
THOUGHT = "volume=0.85,lowpass=f=6500,aecho=0.8:0.4:20:0.12"


def lines():
    en = json.load(open(EN))
    voiced = set(v.strip() for v in gen_lang.VOICES.values())
    out = {}
    for k, v in en.items():
        if k.startswith("line."):
            out["v.you." + k[5:]] = ("thought", v)
    src = open(CUTS).read()
    for cid, body in re.findall(r'cut\("(\w+)"\)(.*?);', src, re.S):
        for i, sp in enumerate(re.findall(r'\.line\(\d+, \d+, "(\w+)"\)', body)):
            t = en[f"cut.{cid}.{i}"]
            if t.strip() in voiced:
                continue
            # in the good ending the voice that asks for the word is really her
            if sp == "lily_q" and cid == "end_dawn":
                sp = "lily"
            out[f"v.cut.{cid}.{i}"] = (sp, t)
    return out


def main():
    from kokoro_onnx import Kokoro
    import soundfile as sf
    k = Kokoro(os.path.join(TTS, "kokoro.onnx"), os.path.join(TTS, "voices.bin"))
    todo = lines()
    made = {}
    for ev, (who, text) in todo.items():
        wav = os.path.join(WORK, ev + ".wav")
        voice = {"lily": "af_bella", "lily_q": "af_bella"}.get(who, "am_liam")
        speed = {"lily_q": 0.9, "thought": 0.95}.get(who, 1.0)
        if not os.path.exists(wav):
            spoken = text.replace("...", ", ").replace("'", "'")
            s, sr = k.create(spoken, voice=voice, speed=speed, lang="en-us")
            sf.write(wav, s, sr)
        out = ev.replace(".", "_")
        if who == "lily":
            chain = f"apad=pad_dur=0.25,{g.ROOM}"
        elif who == "lily_q":
            chain = f"apad=pad_dur=0.6,{g.mimic_chain(g.ROOM)}"
        elif who == "thought":
            chain = f"apad=pad_dur=0.2,{THOUGHT}"
        else:
            chain = "apad=pad_dur=0.2,volume=0.9,lowpass=f=7000"
        g.ff(out, [(wav, [])], f"[0:a]aformat=channel_layouts=mono,aresample=44100,{chain}[x]")
        made[ev] = out
    sj_p = os.path.join(g.A, "sounds.json")
    vl_p = os.path.join(g.A, "voice_lengths.json")
    sj = json.load(open(sj_p))
    vl = json.load(open(vl_p))
    for ev, f in made.items():
        sub = "line." + ev[6:] if ev.startswith("v.you.") else ev[2:]
        sj[ev] = {"sounds": [{"name": f"mimicry:{f}"}], "subtitle": sub}
        d = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", os.path.join(g.SND, f + ".ogg")],
                           capture_output=True, text=True).stdout.strip()
        vl[ev] = int(float(d) * 20)
    json.dump(sj, open(sj_p, "w"), indent=1)
    json.dump(vl, open(vl_p, "w"), indent=1)
    names = ",\n            ".join(", ".join(f'"{n}"' for n in list(made)[i:i + 4]) for i in range(0, len(made), 4))
    open(JAVA, "w").write(f"""package com.krolasyon.mimic.registry;

/** Generated by tools/gen_voices_extra.py: the voiced inner lines and cutscene lines. */
public final class ExtraVoices {{
    public static final String[] NAMES = {{
            {names}
    }};

    private ExtraVoices() {{}}
}}
""")
    print("extra voices", len(made))


if __name__ == "__main__":
    main()
