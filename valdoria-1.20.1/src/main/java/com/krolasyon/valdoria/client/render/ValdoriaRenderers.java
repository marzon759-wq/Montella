package com.krolasyon.valdoria.client.render;

import com.krolasyon.valdoria.ValdoriaMod;
import com.krolasyon.valdoria.entity.Gloomlynx;
import com.krolasyon.valdoria.entity.LumenMoth;
import com.krolasyon.valdoria.entity.Veilstag;
import com.krolasyon.valdoria.entity.Vinestalker;
import com.krolasyon.valdoria.registry.ModEntities;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.math.Axis;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.LivingEntity;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.client.event.EntityRenderersEvent;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;
import software.bernie.geckolib.animatable.GeoEntity;
import software.bernie.geckolib.constant.DataTickets;
import software.bernie.geckolib.core.animatable.model.CoreGeoBone;
import software.bernie.geckolib.core.animation.AnimationState;
import software.bernie.geckolib.model.DefaultedEntityGeoModel;
import software.bernie.geckolib.model.data.EntityModelData;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

/**
 * GeckoLib renderers for the Glimmerveil creatures. Geometry, animations and textures live in
 * geo/entity, animations/entity and textures/entity (generated by tools/gen_entities.py); the
 * {@code _glowmask} textures are drawn full-bright on top (eyes, antler tips, wing veins, spots).
 */
@Mod.EventBusSubscriber(modid = ValdoriaMod.MODID, bus = Mod.EventBusSubscriber.Bus.MOD, value = Dist.CLIENT)
public final class ValdoriaRenderers {
    private ValdoriaRenderers() {}

    @SubscribeEvent
    public static void renderers(EntityRenderersEvent.RegisterRenderers event) {
        event.registerEntityRenderer(ModEntities.VEILSTAG.get(), ctx -> new Renderer<Veilstag>(ctx, new Model<>("veilstag", "neck", "head") {
            @Override
            public void setCustomAnimations(Veilstag e, long id, AnimationState<Veilstag> st) {
                super.setCustomAnimations(e, id, st);
                boolean baby = e.isBaby();
                for (String b : new String[]{"antler_l", "antler_r"}) {
                    CoreGeoBone bone = getAnimationProcessor().getBone(b);
                    if (bone != null) bone.setHidden(baby);
                }
                CoreGeoBone head = getAnimationProcessor().getBone("head");
                if (head != null) {
                    float s = baby ? 1.35F : 1.0F;
                    head.setScaleX(s);
                    head.setScaleY(s);
                    head.setScaleZ(s);
                }
            }
        }, 0.7F) {
            @Override
            public void render(Veilstag e, float yaw, float pt, PoseStack pose, MultiBufferSource buf, int light) {
                pose.pushPose();
                if (e.isBaby()) pose.scale(0.55F, 0.55F, 0.55F);
                super.render(e, yaw, pt, pose, buf, light);
                pose.popPose();
            }
        });
        event.registerEntityRenderer(ModEntities.GLOOMLYNX.get(), ctx -> new Renderer<Gloomlynx>(ctx, new Model<>("gloomlynx", null, "head") {
            @Override
            protected boolean tracksHead(Gloomlynx e) {
                return !e.isNapping();
            }
        }, 0.5F));
        event.registerEntityRenderer(ModEntities.VINESTALKER.get(), ctx -> new Renderer<Vinestalker>(ctx, new Model<>("vinestalker", null, "head"), 0.8F) {
            @Override
            protected void applyRotations(Vinestalker e, PoseStack pose, float age, float yaw, float pt) {
                super.applyRotations(e, pose, age, yaw, pt);
                if (e.isHanging()) {
                    // clings upside-down under the branch
                    pose.translate(0, e.getBbHeight() + 0.05F, 0);
                    pose.mulPose(Axis.ZP.rotationDegrees(180));
                }
            }
        });
        event.registerEntityRenderer(ModEntities.LUMEN_MOTH.get(), ctx -> new Renderer<LumenMoth>(ctx, new Model<>("lumen_moth", null, null), 0.0F) {
            @Override
            public void render(LumenMoth e, float yaw, float pt, PoseStack pose, MultiBufferSource buf, int light) {
                pose.pushPose();
                pose.scale(0.6F, 0.6F, 0.6F);
                super.render(e, yaw, pt, pose, buf, 0xF000F0);
                pose.popPose();
            }
        });
    }

    /** Model with optional head tracking spread over a neck bone and a head bone. */
    static class Model<T extends LivingEntity & GeoEntity> extends DefaultedEntityGeoModel<T> {
        private final String neck, head;

        Model(String name, String neck, String head) {
            super(ValdoriaMod.id(name));
            this.neck = neck;
            this.head = head;
        }

        protected boolean tracksHead(T e) {
            return true;
        }

        @Override
        public RenderType getRenderType(T animatable, ResourceLocation texture) {
            return RenderType.entityCutoutNoCull(texture);
        }

        @Override
        public void setCustomAnimations(T e, long id, AnimationState<T> st) {
            super.setCustomAnimations(e, id, st);
            if (head == null || !tracksHead(e)) return;
            EntityModelData d = st.getData(DataTickets.ENTITY_MODEL_DATA);
            if (d == null) return;
            float yaw = Mth.clamp(d.netHeadYaw(), -70, 70) * Mth.DEG_TO_RAD;
            float pitch = Mth.clamp(d.headPitch(), -40, 40) * Mth.DEG_TO_RAD;
            CoreGeoBone h = getAnimationProcessor().getBone(head);
            CoreGeoBone n = neck == null ? null : getAnimationProcessor().getBone(neck);
            if (n != null) {
                n.setRotY(n.getRotY() + yaw * 0.5F);
                n.setRotX(n.getRotX() + pitch * 0.3F);
                if (h != null) h.setRotY(h.getRotY() + yaw * 0.4F);
            } else if (h != null) {
                h.setRotY(h.getRotY() + yaw);
                h.setRotX(h.getRotX() + pitch);
            }
        }
    }

    static class Renderer<T extends LivingEntity & GeoEntity> extends GeoEntityRenderer<T> {
        Renderer(EntityRendererProvider.Context ctx, Model<T> model, float shadow) {
            super(ctx, model);
            this.shadowRadius = shadow;
            addRenderLayer(new AutoGlowingGeoLayer<>(this));
        }
    }
}
