package com.krolasyon.kaiju.client;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.krolasyon.kaiju.KaijuMod;
import com.krolasyon.kaiju.entity.KaijuEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * Plain vanilla model (no GeckoLib). The geometry - a few hundred parts and about two thousand box-UV cubes - is
 * generated by tools/gen_kaiju.py and shipped as assets/kaiju/models/entity/kaiju.json; this class turns it into a
 * MeshDefinition exactly the way a hand-written createBodyLayer() would, and animates the named bones.
 */
public class KaijuModel extends HierarchicalModel<KaijuEntity> {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(KaijuMod.MODID, "kaiju"), "main");
    private static final String GEOMETRY = "/assets/kaiju/models/entity/kaiju.json";
    private static final int TAIL = 12;

    private final ModelPart root;
    private final ModelPart body, torso, neck, head, jaw;
    private final ModelPart[] arm = new ModelPart[2], forearm = new ModelPart[2], hand = new ModelPart[2];
    private final ModelPart[] thigh = new ModelPart[2], shin = new ModelPart[2], foot = new ModelPart[2];
    private final ModelPart[] tail = new ModelPart[TAIL];

    public KaijuModel(ModelPart root) {
        this.root = root;
        Map<String, ModelPart> parts = new HashMap<>();
        JsonObject geo = load();
        for (JsonElement e : geo.getAsJsonArray("parts")) {
            JsonObject p = e.getAsJsonObject();
            String name = p.get("name").getAsString();
            ModelPart parent = p.get("parent").isJsonNull() ? root : parts.get(p.get("parent").getAsString());
            parts.put(name, parent.getChild(name));
        }
        body = parts.get("body");
        torso = parts.get("torso");
        neck = parts.get("neck");
        head = parts.get("head");
        jaw = parts.get("jaw");
        String[] side = {"l", "r"};
        for (int i = 0; i < 2; i++) {
            arm[i] = parts.get("arm_" + side[i]);
            forearm[i] = parts.get("forearm_" + side[i]);
            hand[i] = parts.get("hand_" + side[i]);
            thigh[i] = parts.get("thigh_" + side[i]);
            shin[i] = parts.get("shin_" + side[i]);
            foot[i] = parts.get("foot_" + side[i]);
        }
        for (int i = 0; i < TAIL; i++) tail[i] = parts.get("tail" + i);
    }

    private static JsonObject load() {
        try (InputStream in = KaijuModel.class.getResourceAsStream(GEOMETRY)) {
            if (in == null) throw new IllegalStateException("missing " + GEOMETRY);
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
        } catch (java.io.IOException ex) {
            throw new RuntimeException(ex);
        }
    }

    public static LayerDefinition createBodyLayer() {
        JsonObject geo = load();
        MeshDefinition mesh = new MeshDefinition();
        Map<String, PartDefinition> defs = new HashMap<>();
        for (JsonElement e : geo.getAsJsonArray("parts")) {
            JsonObject p = e.getAsJsonObject();
            String name = p.get("name").getAsString();
            PartDefinition parent = p.get("parent").isJsonNull() ? mesh.getRoot() : defs.get(p.get("parent").getAsString());
            CubeListBuilder cubes = CubeListBuilder.create();
            for (JsonElement ce : p.getAsJsonArray("cubes")) {
                JsonArray c = ce.getAsJsonArray();
                cubes.texOffs(c.get(0).getAsInt(), c.get(1).getAsInt())
                        .addBox(c.get(2).getAsFloat(), c.get(3).getAsFloat(), c.get(4).getAsFloat(),
                                c.get(5).getAsFloat(), c.get(6).getAsFloat(), c.get(7).getAsFloat());
            }
            JsonArray pv = p.getAsJsonArray("pivot"), r = p.getAsJsonArray("rot");
            defs.put(name, parent.addOrReplaceChild(name, cubes, PartPose.offsetAndRotation(
                    pv.get(0).getAsFloat(), pv.get(1).getAsFloat(), pv.get(2).getAsFloat(),
                    r.get(0).getAsFloat(), r.get(1).getAsFloat(), r.get(2).getAsFloat())));
        }
        JsonArray tex = geo.getAsJsonArray("texture");
        return LayerDefinition.create(mesh, tex.get(0).getAsInt(), tex.get(1).getAsInt());
    }

    @Override
    public ModelPart root() {
        return root;
    }

    @Override
    public void setupAnim(KaijuEntity e, float swing, float amount, float age, float headYaw, float headPitch) {
        root.getAllParts().forEach(ModelPart::resetPose);
        float walk = Math.min(1.0F, amount * 1.6F);
        float ph = swing * 0.22F;               // slow, heavy stride
        float s = Mth.sin(ph), c = Mth.cos(ph);

        // breathing
        float breath = Mth.sin(age * 0.045F);
        torso.xRot += breath * 0.015F;
        neck.xRot -= breath * 0.02F;
        head.xRot += breath * 0.01F;
        jaw.xRot += (0.5F + 0.5F * Mth.sin(age * 0.03F)) * 0.06F;

        // gait: legs swing in opposition, the body rolls onto the planted leg and bobs on each step
        thigh[0].xRot += s * 0.38F * walk;
        thigh[1].xRot -= s * 0.38F * walk;
        shin[0].xRot += Math.max(0.0F, -c) * 0.42F * walk;
        shin[1].xRot += Math.max(0.0F, c) * 0.42F * walk;
        foot[0].xRot -= s * 0.22F * walk;
        foot[1].xRot += s * 0.22F * walk;
        body.zRot += s * 0.045F * walk;
        body.y += Math.abs(c) * 1.6F * walk;
        torso.yRot -= s * 0.05F * walk;
        torso.xRot += 0.05F * walk;
        arm[0].xRot -= s * 0.14F * walk;
        arm[1].xRot += s * 0.14F * walk;

        // tail: a travelling wave, bigger while walking
        float amp = 0.035F + 0.05F * walk;
        for (int i = 0; i < TAIL; i++) {
            tail[i].yRot += Mth.sin(age * 0.06F + swing * 0.11F - i * 0.45F) * amp * (0.6F + i * 0.08F);
            tail[i].xRot += Mth.sin(age * 0.04F - i * 0.35F) * 0.012F;
        }

        // look: neck takes part of the turn, head the rest
        float yaw = headYaw * Mth.DEG_TO_RAD, pitch = headPitch * Mth.DEG_TO_RAD;
        neck.yRot += yaw * 0.4F;
        head.yRot += yaw * 0.6F;
        neck.xRot += pitch * 0.4F;
        head.xRot += pitch * 0.6F;

        // arms hang heavy, fingers flex
        for (int i = 0; i < 2; i++) {
            float sg = i == 0 ? 1 : -1;
            arm[i].zRot += sg * Mth.sin(age * 0.05F + i) * 0.03F;
            forearm[i].xRot += Mth.sin(age * 0.045F + i) * 0.04F;
            hand[i].xRot += Mth.sin(age * 0.07F + i * 2) * 0.05F;
        }
    }
}
