"""Turns the Java mod's story data into TypeScript for the Bedrock script: the lines (who says them, how long),
the choices, every animation's index, and the cutscenes themselves (Cuts.java's builder chain, translated)."""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
JAVA = os.path.abspath(os.path.join(ROOT, "..", "common", "src", "main"))
STORY = os.path.join(JAVA, "java", "com", "krolasyon", "bloodsea", "story")
JA = os.path.join(JAVA, "resources", "assets", "bloodsea")
SRC = os.path.join(ROOT, "src")


def lines():
    src = open(os.path.join(STORY, "Lines.java")).read()
    L = {m.group(1): [m.group(2), int(m.group(3))] for m in re.finditer(r'e\("([^"]+)", "([^"]+)", (\d+)\)', src)}
    C = {m.group(1): re.findall(r'"([^"]+)"', m.group(2)) for m in re.finditer(r'Map\.entry\("(\w+)", new String\[\]\{([^}]*)\}\)', src)}
    out = "// generated by tools/gen_ts_data.py from the Java mod\n"
    out += "export const LINES: Record<string, [string, number]> = " + json.dumps(L) + ";\n"
    out += "export const CHOICES: Record<string, string[]> = " + json.dumps(C) + ";\n"
    open(os.path.join(SRC, "lines.gen.ts"), "w").write(out)


def anims():
    A = {}
    for n, model in (("raft", "raft"), ("elias", "elias"), ("rescuer", "elias"), ("pip", "pip"), ("wake", "wake"), ("gatherer", "gatherer"),
                     ("caller", "caller"), ("changer", "changer"), ("leviathan", "leviathan")):
        d = json.load(open(os.path.join(JA, "animations", f"{model}.animation.json")))
        A[n] = [[k.split(".")[-1], round(float(v.get("animation_length", 1)) * 20)] for k, v in d["animations"].items()]
    open(os.path.join(SRC, "anims.gen.ts"), "w").write(
        "// generated by tools/gen_ts_data.py: every animation of every entity, in property order, with its length in ticks\n"
        "export const ANIMS: Record<string, [string, number][]> = " + json.dumps(A) + ";\n")


def cuts():
    src = open(os.path.join(STORY, "Cuts.java")).read()
    body = src[src.index("static {") + len("static {"): src.rindex("private Cuts()")]
    body = body[:body.rindex("}")]
    # the few lines that touch Minecraft's own classes
    body = re.sub(r"s\.drop\(new net\.minecraft\.world\.item\.ItemStack\(net\.minecraft\.world\.item\.Items\.BREAD\),", 's.drop("minecraft:bread",', body)
    body = re.sub(r"s\.drop\(com\.krolasyon\.bloodsea\.compat\.Compat\.named\(new net\.minecraft\.world\.item\.ItemStack\(net\.minecraft\.world\.item\.Items\.COD\),\s*"
                  r"net\.minecraft\.network\.chat\.Component\.translatable\(\"item\.bloodsea\.pip_fish\"\)\),", 's.drop("minecraft:cod",', body)
    body = re.sub(r"s\.lvl\(\)\.getEntitiesOfClass\(net\.minecraft\.world\.entity\.item\.ItemEntity\.class, s\.p\.getBoundingBox\(\)\.inflate\(12\)\)\.forEach\(e -> e\.discard\(\)\)",
                  "s.clearItems()", body)
    if "net.minecraft" in body or "com.krolasyon" in body:
        bad = [l for l in body.splitlines() if "net.minecraft" in l or "com.krolasyon" in l]
        raise SystemExit("untranslated Java left in the cuts:\n" + "\n".join(bad))
    body = body.replace("s -> {", "(s) => {")
    body = re.sub(r"\bs -> ", "(s) => ", body)
    body = re.sub(r"(\d)f\b", r"\1", body)
    out = ("// generated by tools/gen_ts_data.py from Cuts.java: the eighteen cutscenes, shot by shot\n"
           "import { cut, v } from \"./cutlib\";\n\n"
           "export function defineCuts(): void {\n" + body + "\n}\n")
    open(os.path.join(SRC, "cuts.gen.ts"), "w").write(out)


if __name__ == "__main__":
    os.makedirs(SRC, exist_ok=True)
    lines()
    anims()
    cuts()
    print("ok")
