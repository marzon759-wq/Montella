package com.krolasyon.beyblade.client;

import com.krolasyon.beyblade.entity.BeffalEntity;
import com.krolasyon.beyblade.entity.BeybladeEntity;
import com.krolasyon.beyblade.entity.CommonBeybladeEntity;
import com.krolasyon.beyblade.entity.EagleEntity;
import com.krolasyon.beyblade.entity.LDragoEntity;
import com.krolasyon.beyblade.entity.LeoneEntity;
import com.krolasyon.beyblade.entity.PegasusEntity;
import com.krolasyon.beyblade.entity.TempoEntity;
import com.krolasyon.beyblade.entity.VariaresEntity;
import com.krolasyon.beyblade.parts.BeyPart;

/**
 * Which GeckoLib animation plays when. The keyframes themselves are in
 * assets/librabeyblade/animations/beyblade.animation.json (generated by tools/gen_geo.py).
 *
 * Three controllers:
 *  body   - looping state of the whole bey: spinning, low spin chatter, airborne, sleep out, burst, recall
 *  tip    - looping behaviour of the performance tip: rubber grip, ball roll, free spin bearing, sharp, flat
 *  action - one shots: hits, landing, launch, special moves
 */
public final class BeyAnims {
   public static final String PREFIX = "animation.beyblade.";
   public static final String BODY = "body";
   public static final String TIP = "tip";
   public static final String ACTION = "action";

   public static final String HIT_LIGHT = "hit_light";
   public static final String HIT_HEAVY = "hit_heavy";
   public static final String HIT_WALL = "hit_wall";
   public static final String LAND = "land";
   public static final String LAUNCH = "launch";
   public static final String EVADE = "evade";
   public static final String SHIELD_HIT = "shield_hit";
   public static final String GRIND = "grind";
   public static final String CLASH = "special_clash";
   public static final String SPIRIT = "spirit";
   public static final String XDASH = "xtreme_dash";
   public static final String RAIL = "rail";
   // special move archetypes
   public static final String SP_AWAKEN = "sp_awaken";
   public static final String SP_DIVE = "sp_dive";
   public static final String SP_DRILL = "sp_drill";
   public static final String SP_DASH = "sp_dash";
   public static final String SP_VORTEX = "sp_vortex";
   public static final String SP_GUARD = "sp_guard";
   public static final String SP_STEAL = "sp_steal";
   public static final String SP_LEVITATE = "sp_levitate";
   public static final String SP_FINISHER = "sp_finisher";
   public static final String SP_UPPER = "sp_upper";

   public static final String[] ACTIONS = {
      HIT_LIGHT, HIT_HEAVY, HIT_WALL, LAND, LAUNCH, EVADE, SHIELD_HIT, GRIND, CLASH, SPIRIT, XDASH, RAIL,
      SP_AWAKEN, SP_DIVE, SP_DRILL, SP_DASH, SP_VORTEX, SP_GUARD, SP_STEAL, SP_LEVITATE, SP_FINISHER, SP_UPPER
   };

   private BeyAnims() {
   }

   public static String full(String name) {
      return PREFIX + name;
   }

   /** Animations that stop on their last frame instead of looping. */
   public static boolean hold(String name) {
      return name.equals("sleep_out") || name.equals("burst");
   }

   public static String bodyLoop(BeybladeEntity e) {
      int st = e.getState();
      if (st == BeybladeEntity.STATE_DEFEATED) {
         return e.burstFinish() ? "burst" : "sleep_out";
      }
      if (st == BeybladeEntity.STATE_RECALL) {
         return "recall";
      }
      if (!e.onGround() && e.tickCount - e.landTime > 3) {
         return "airborne";
      }
      float r = e.spinRatio();
      if (r < 0.22F) {
         return "spin_dying";
      }
      return r < 0.45F ? "spin_low" : "spin";
   }

   public static String tipLoop(BeybladeEntity e) {
      if (e.getState() != BeybladeEntity.STATE_BATTLE) {
         return "tip_idle";
      }
      BeyPart.Tip t = e.parts().tip();
      if (t.rubber()) {
         return "tip_rubber";
      }
      if (t.ball()) {
         return "tip_ball";
      }
      if (t.freeSpin()) {
         return "tip_bearing";
      }
      if (t.sharp()) {
         return "tip_sharp";
      }
      return "tip_flat";
   }

   /** Special move archetype for ability {@code ab} of this bey. */
   public static String ability(BeybladeEntity e, int ab) {
      if (e instanceof CommonBeybladeEntity) {
         return switch (ab) {
            case 1 -> SP_DASH;
            case 2 -> SP_GUARD;
            default -> switch (e.getMode()) {
               case BeybladeEntity.MODE_ATTACK -> SP_UPPER;
               case BeybladeEntity.MODE_DEFENSE -> SP_GUARD;
               case BeybladeEntity.MODE_STAMINA -> SP_AWAKEN;
               default -> SP_VORTEX;
            };
         };
      }
      if (e instanceof LDragoEntity) {
         return switch (ab) {
            case 1 -> SP_AWAKEN;
            case 2 -> SP_STEAL;
            case 3 -> SP_DIVE;
            case 4 -> SP_DASH;
            default -> SP_FINISHER;
         };
      }
      if (e instanceof LeoneEntity) {
         return switch (ab) {
            case 1 -> SP_GUARD;
            case 2 -> SP_DASH;
            case 3 -> SP_UPPER;
            case 4 -> SP_DRILL;
            default -> SP_VORTEX;
         };
      }
      if (e instanceof EagleEntity) {
         return switch (ab) {
            case 1 -> SP_AWAKEN;
            case 2 -> SP_VORTEX;
            case 3 -> SP_DIVE;
            case 4 -> SP_DASH;
            default -> SP_FINISHER;
         };
      }
      if (e instanceof PegasusEntity) {
         return switch (ab) {
            case 1 -> SP_AWAKEN;
            case 2 -> SP_VORTEX;
            case 3 -> SP_DIVE;
            case 4 -> SP_DASH;
            default -> SP_DIVE;
         };
      }
      if (e instanceof TempoEntity) {
         return switch (ab) {
            case 1, 2 -> SP_LEVITATE;
            case 3 -> SP_VORTEX;
            case 4 -> SP_AWAKEN;
            default -> SP_FINISHER;
         };
      }
      if (e instanceof VariaresEntity) {
         return switch (ab) {
            case 1 -> SP_AWAKEN;
            case 2, 3 -> SP_DASH;
            case 4 -> SP_VORTEX;
            default -> SP_FINISHER;
         };
      }
      if (e instanceof BeffalEntity) {
         return switch (ab) {
            case 1 -> SP_GUARD;
            case 2, 4 -> SP_LEVITATE;
            case 3 -> SP_VORTEX;
            default -> SP_FINISHER;
         };
      }
      // Flame Libra (and its rival)
      return switch (ab) {
         case 1 -> SP_VORTEX;
         case 2 -> SP_GUARD;
         case 3 -> SP_DRILL;
         case 4 -> SP_DASH;
         default -> SP_FINISHER;
      };
   }
}
